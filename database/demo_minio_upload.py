def ensure_bucket(client, bucket: str) -> None:
    if not client.bucket_exists(bucket):
        client.make_bucket(bucket)
        print(f"  Bucket creato: {bucket}")


def upload(client, bucket: str, key: str, data: bytes) -> None:
    client.put_object(bucket, key, io.BytesIO(data), length=len(data), content_type="image/jpeg")
    print(f"  OK  {key} ({len(data)} bytes)")


def main():
    parser = argparse.ArgumentParser(description="Carica immagini demo rx_panoramica in MinIO")
    parser.add_argument("--endpoint", default="127.0.0.1:9000")
    parser.add_argument("--key", default="fpapale")
    parser.add_argument("--secret", default="ViaGoceano2021")
    parser.add_argument("--secure", action="store_true")
    args = parser.parse_args()

    from minio import Minio
    client = Minio(args.endpoint, access_key=args.key, secret_key=args.secret, secure=args.secure)

    ensure_bucket(client, BUCKET)

    for entry in DEMO_IMAGES:
        local_path = os.path.join(DEMO_IMAGES_DIR, entry["local_name"])
        if os.path.exists(local_path):
            with open(local_path, "rb") as fh:
                data = fh.read()
            print(f"Uploading (real): {entry['local_name']}")
        else:
            data = minimal_jpeg()
            print(f"Uploading (placeholder): {entry['local_name']}")
        upload(client, BUCKET, entry["object_key"], data)

    print("\nDone. Per immagini reali, copia i JPG in database/demo-images/ e riesegui.")


if __name__ == "__main__":
    main()
